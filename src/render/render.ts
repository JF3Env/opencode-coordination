import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import type { Ledger } from "../ledger/ledger.ts"
import type { Profile } from "../config/profile.ts"
import type { Item, Stage } from "../domain/types.ts"
import { computeBoard, freeEngineers, NO_FRONT } from "../views/board.ts"
import { isActive } from "../domain/items.ts"

export interface Page {
  path: string
  content: string
}

const HEADER = "<!-- Generated by opencode-coordination (coordination render). Do not edit: the next render replaces this file. -->"

// A table cell is one line and never holds a pipe.
const cell = (value: unknown): string => String(value ?? "").replace(/\s+/g, " ").replaceAll("|", "\\|").trim() || "—"

const outcome = (item: Item) => (item.outcome.moves ? `Moves: ${item.outcome.moves}` : `Upkeep: ${item.outcome.upkeep ?? "—"}${item.outcome.enables ? `; Enables: ${item.outcome.enables}` : ""}`)

function stageCell(item: Item, stage: Stage): string {
  const s = item.stages[stage]
  return s ? `${s.at.slice(0, 10)}${s.commit ? ` · ${s.commit.slice(0, 8)}` : ""}` : "—"
}

function table(head: string[], rows: string[][]): string {
  return [`| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`, ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`)].join("\n")
}

export function activePage(ledger: Ledger): string {
  const active = ledger.items(isActive).sort((a, b) => a.id.localeCompare(b.id))
  const holds = ledger.holds()
  const free = freeEngineers(ledger)
  return [
    HEADER, "", "# Active work", "",
    active.length
      ? table(["Item", "Title", "State", "Engineer", "Branch", "Worktree", "PR", "Files", "Outcome"], active.map((i) => [i.id, i.title, i.state, i.assigneeName ?? "", i.branch ?? "", i.worktree ?? "", i.pr ? `#${i.pr}` : "", i.scopeFiles.join(", "), outcome(i)]))
      : "Nothing is being worked on.",
    "", "## Holds", "",
    holds.length ? table(["Hold", "Kind", "Covers", "Reason", "Ends when"], holds.map((h) => [h.id, h.kind, h.kind === "freeze" ? "everything" : [...h.paths, ...h.prs.map((p) => `PR #${p}`)].join(", "), h.reason, h.liftOn])) : "No active hold.",
    "", "## Free engineers", "", free.length ? free.map((a) => `- ${a.name}`).join("\n") : "None.", "",
  ].join("\n")
}

export function boardPage(ledger: Ledger, profile: Profile): string {
  const board = computeBoard(ledger, profile)
  const out = [HEADER, "", "# Board", ""]
  for (const f of board.fronts) {
    out.push(`## ${f.id}${f.title ? ` — ${f.title}` : ""}`, "")
    if (f.parked) out.push(`Parked: ${f.parked.reason} (until ${f.parked.unparkOn}).`, "")
    const row = (i: Item) => [i.id, i.title, i.state, i.assigneeName ?? "", outcome(i)]
    for (const [name, items] of [["Now", f.now], ["Next", f.next], ["Later", f.later]] as const) {
      out.push(`**${name}**`, "", items.length ? table(["Item", "Title", "State", "Engineer", "Outcome"], items.map(row)) : "—", "")
    }
    if (f.measures.length) out.push("**Latest measures**", "", table(["Measure", "Value", "Record"], f.measures.map((m) => [m.name, `${m.value} ${m.unit}`.trim(), m.claimed ? `${m.record} (claim: not on main)` : m.record])), "")
  }
  return out.join("\n")
}

export function roadmapPage(ledger: Ledger, profile: Profile): string {
  const board = computeBoard(ledger, profile)
  const summaries = new Map(ledger.summaries().filter((s) => s.kind === "front").map((s) => [s.key, s.text]))
  const out = [HEADER, "", "# Roadmap", "", "Every stage shows its date and the commit it was read from. A blank stage is not done.", ""]
  for (const f of board.fronts) {
    const items = ledger.items((i) => (i.front ?? NO_FRONT) === f.id && !["rejected", "cancelled"].includes(i.state)).sort((a, b) => (a.priority ?? 1e9) - (b.priority ?? 1e9) || a.id.localeCompare(b.id))
    if (!items.length && !summaries.has(f.id)) continue
    out.push(`## ${f.id}${f.title ? ` — ${f.title}` : ""}`, "", summaries.get(f.id) ?? "", "")
    out.push(table(["Item", "State", "Planned", "Specified", "Implemented", "Tested", "Validated"], items.map((i) => [`${i.id} ${i.title}`, i.state, stageCell(i, "planned"), stageCell(i, "specified"), stageCell(i, "implemented"), stageCell(i, "tested"), stageCell(i, "validated")])), "")
  }
  return out.join("\n")
}

export function statusPage(ledger: Ledger, profile: Profile): string {
  const summaries = ledger.summaries()
  const of = (kind: string) => summaries.filter((s) => s.kind === kind)
  const items = ledger.items()
  const built = items.filter((i) => ["merged", "measured", "validated"].includes(i.state)).length
  const validated = items.filter((i) => i.state === "validated").length
  const bullets = (xs: Array<{ key: string; text: string }>, empty: string) => (xs.length ? xs.map((s) => `- ${s.text}`).join("\n") : empty)
  const fronts = of("front")
  const titled = (key: string) => profile.fronts.find((f) => f.id === key)?.title
  return [
    HEADER, "", "# Project status", "",
    `Built: ${built} piece(s) of work. Checked against an independent reference: ${validated}. In progress: ${items.filter(isActive).length}.`, "",
    "## Where each goal stands", "", bullets(fronts.map((s) => ({ key: s.key, text: titled(s.key) ? `${titled(s.key)}: ${s.text}` : s.text })), "No goal has a status line yet."), "",
    "## Risks", "", bullets(of("risk").slice(0, 3), "None reported."), "",
    "## What needs the sponsor", "", bullets(of("decision"), "Nothing at the moment."), "",
  ].join("\n")
}

export function snapshot(ledger: Ledger): string {
  const clean = <T extends object>(x: T): T => JSON.parse(JSON.stringify(x))
  return `${JSON.stringify({
    items: clean(ledger.items()),
    agents: ledger.agents((a) => a.role !== "other").map((a) => ({ name: a.name, role: a.role, status: a.status, kind: a.kind, directory: a.directory })).sort((a, b) => a.name.localeCompare(b.name)),
    holds: ledger.holds(),
    decisions: ledger.decisions(),
    measures: ledger.measures(),
    summaries: ledger.summaries(),
  }, null, 2)}\n`
}

export function renderPages(ledger: Ledger, profile: Profile): Page[] {
  const r = profile.render
  return [
    { path: r.active, content: activePage(ledger) },
    { path: r.board, content: boardPage(ledger, profile) },
    { path: r.roadmap, content: roadmapPage(ledger, profile) },
    { path: r.status, content: statusPage(ledger, profile) },
    { path: r.snapshot, content: snapshot(ledger) },
  ]
}

export function writePages(root: string, pages: Page[]): string[] {
  const changed: string[] = []
  for (const page of pages) {
    const file = join(root, page.path)
    if (existsSync(file) && readFileSync(file, "utf8") === page.content) continue
    mkdirSync(dirname(file), { recursive: true })
    writeFileSync(file, page.content)
    changed.push(page.path)
  }
  return changed
}

/** Paths whose content differs from a fresh render: a hand edit or a stale page. Empty means current. */
export function stalePages(root: string, pages: Page[]): string[] {
  return pages.filter((page) => {
    const file = join(root, page.path)
    return !existsSync(file) || readFileSync(file, "utf8") !== page.content
  }).map((page) => page.path)
}
