// Writes docs/TOOLS.md from the tool registry, so the documentation cannot drift from the code.
// Run: node scripts/gen-docs.ts          Check: node scripts/gen-docs.ts --check
import { readFileSync, writeFileSync } from "node:fs"
import { ALL_TOOLS } from "../src/tools/index.ts"

const first = (text: string) => text.split(/(?<=[.!?])\s/)[0] ?? text

export function toolsDoc(): string {
  const roles = (t: (typeof ALL_TOOLS)[number]) => (t.roles === "any" ? "any" : t.roles.join(", "))
  const groups: Array<[string, (t: (typeof ALL_TOOLS)[number]) => boolean]> = [
    ["Every role", (t) => t.roles === "any"],
    ["Engineer", (t) => t.roles !== "any" && t.roles.length === 1 && t.roles[0] === "engineer"],
    ["Coordinator", (t) => t.roles !== "any" && t.roles.length === 1 && t.roles[0] === "coordinator"],
    ["Product manager", (t) => t.roles !== "any" && t.roles.length === 1 && t.roles[0] === "product-manager"],
    ["Shared between roles", (t) => t.roles !== "any" && t.roles.length > 1],
  ]
  const out = ["<!-- Generated by scripts/gen-docs.ts from the tool registry. Do not edit. -->", "", "# Tools", "",
    "Every tool is published as `coordination_<name>`. The role is read from the session's agent id; a tool called by another role is refused and the refusal is recorded as an event.", ""]
  for (const [title, pick] of groups) {
    const tools = ALL_TOOLS.filter(pick)
    if (!tools.length) continue
    out.push(`## ${title}`, "", "| Tool | Roles | What it does |", "| --- | --- | --- |", ...tools.map((t) => `| \`${t.name}\` | ${roles(t)} | ${first(t.description).replaceAll("|", "\\|")} |`), "")
  }
  return `${out.join("\n")}`
}

if (process.argv[1]?.endsWith("gen-docs.ts")) {
  const target = new URL("../docs/TOOLS.md", import.meta.url)
  const content = toolsDoc()
  if (process.argv.includes("--check")) {
    const current = (() => { try { return readFileSync(target, "utf8") } catch { return "" } })()
    if (current !== content) {
      console.error("docs/TOOLS.md is stale: run node scripts/gen-docs.ts")
      process.exit(1)
    }
  } else writeFileSync(target, content)
}
